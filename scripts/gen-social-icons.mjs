/**
 * Regenerate `src/config/socialIcons.ts` from the `simple-icons` dev dependency.
 *
 * Only the ~19 slugs referenced by SOCIAL_NETWORKS are extracted, so the shipped
 * bundle carries a few KB of path data instead of a 3,000-icon package. The
 * icons are CC0-1.0, so embedding them is fine.
 *
 * Run: `npm run gen:icons`
 */
import { readFileSync, writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

const source = readFileSync('src/config/social.ts', 'utf8')
const slugs = [...source.matchAll(/slug:\s*'([^']+)'/g)].map((m) => m[1])
if (!slugs.length) throw new Error('no slugs found in src/config/social.ts')

/**
 * Slugs Simple Icons does not carry. LinkedIn was removed from the set after a
 * trademark takedown, which is why `cdn.simpleicons.org/linkedin/white` has been
 * returning 404 — the icon was silently broken for everyone. Drawn on the same
 * 24x24 grid so it sits flush with the rest.
 */
const EXTRA_PATHS = {
  linkedin:
    'M6.94 21.5H2.56V9.4h4.38zM4.75 7.45a2.54 2.54 0 1 1 0-5.08 2.54 2.54 0 0 1 0 5.08zM21.5 21.5h-4.37v-6.4c0-1.71-.62-2.6-1.94-2.6-1.05 0-1.67.7-1.95 1.4-.1.25-.08.6-.08.94v6.66H8.82s.06-11.03 0-12.1h4.34v1.9c.26-.85 1.64-2.06 3.85-2.06 2.73 0 4.49 1.78 4.49 5.62z',
}

/** Export names are not a clean slug transform (siLinkedin vs siLinkedIn), so index by the icon's own slug. */
const bySlug = new Map(Object.values(si).map((i) => [i.slug, i]))

const entries = slugs.map((slug) => {
  const path = bySlug.get(slug)?.path ?? EXTRA_PATHS[slug]
  if (!path) throw new Error(`no glyph for slug "${slug}" — add it to EXTRA_PATHS`)
  if (path.includes("'")) throw new Error(`quote in path for "${slug}"`)
  return `  '${slug}': '${path}',`
})

writeFileSync(
  'src/config/socialIcons.ts',
  `/**
 * Simple Icons glyph geometry (CC0-1.0), inlined so the social block never
 * calls out to a CDN — not while editing, and not from a recipient's inbox.
 *
 * GENERATED by scripts/gen-social-icons.mjs — do not edit by hand.
 * simple-icons v${JSON.parse(readFileSync('node_modules/simple-icons/package.json', 'utf8')).version}
 */
export const SOCIAL_ICON_PATHS: Record<string, string> = {
${entries.join('\n')}
}
`,
)
console.log(`wrote src/config/socialIcons.ts — ${entries.length} icons`)
